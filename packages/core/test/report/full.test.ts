import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { runReportMarkdown } from '../../src/report';
import type { RunView } from '../../src/run/types';
import { file, fixedTime, metrics, review, STARTED, step, successRun, workflow } from './fixtures';

const NB = '\u00a0\u00a0';
const full = (input: Parameters<typeof runReportMarkdown>[0]) =>
  runReportMarkdown(input, { formatTime: fixedTime });

beforeEach(() => {
  vi.useFakeTimers();
  vi.setSystemTime(STARTED + 300_000);
});

afterEach(() => {
  vi.useRealTimers();
});

describe('runReportMarkdown: full', () => {
  it('reports a finished run with workflow, review and prices', () => {
    const report = full({
      run: successRun(),
      workflow: workflow(),
      workflowPath: '.isarflow/workflows/review.isarflow.yaml',
      review: review([
        file('src/a.ts', { decision: 'kept' }),
        file('img.png', {
          binary: true,
          additions: undefined,
          deletions: undefined,
          status: 'added',
          stepIds: [],
        }),
        file('docs/old.md', {
          status: 'deleted',
          additions: 0,
          deletions: 40,
          decision: 'reverted',
          stepIds: ['fix', 'review'],
        }),
      ]),
      prices: { 'openai/gpt': { input: 2.5, output: 10 } },
    });

    expect(report).toBe(`# Run report: Review loop

| Run | \`run-42\` |
| --- | --- |
| Status | Succeeded |
| Started | T+0s |
| Duration | 4m 12s |
| Tokens (in / out) | 12,345 / 678 |
| Cost | 0.04 (estimated; no price for local/llama) |
| Workflow | \`.isarflow/workflows/review.isarflow.yaml\` |
| Inputs | branch: main<br>notes: a\\|b c |

## Timeline

| Block | Type | Status | Time | Tokens | Model | Runs |
| --- | --- | --- | --- | --- | --- | --- |
| Run tests (\`tests\`) | Console | Succeeded | 3.2s | — | — | 1 |
| \`review-loop\` | Loop | Succeeded | 3m 20s | — | — | 1 |
| ${NB}\`review\` | Agent | Succeeded | 2m 0s | 12,000 / 600 | openai/gpt | 2 |
| ${NB}\`fix\` | Agent | Succeeded | 1m 0s | 345 / 78 | local/llama | 1 |
| \`pick\` | Ask | Succeeded | 1m 0s | — | — | 1 |
| \`approve\` | Approval | Succeeded | 5s | — | — | 1 |
| \`deploy\` | Console | Not run | — | — | — | — |

## Changed files

3 files changed: 1 kept, 1 reverted, 1 pending.

| File | Changes | Status | Decision | Blocks |
| --- | --- | --- | --- | --- |
| \`src/a.ts\` | +12 −3 | Modified | Kept | \`fix\` |
| \`img.png\` | binary | Added | Pending | Command |
| \`docs/old.md\` | +0 −40 | Deleted | Reverted | \`fix\`, \`review\` |

## Agent answers

### \`review\`

Looks good | ship it

### \`fix\`

Fixed \`foo\`.

## Questions and approvals

- \`pick\`: Which environment?
  - Answer: staging (default used)
- \`approve\`: Deploy?
  - Approved. Comment: Looks \\<fine>

---

Generated by Isar Flow on T+300s.
`);
  });

  it('works without workflow, review, prices and options (default UTC times)', () => {
    const report = runReportMarkdown({ run: successRun() });
    expect(report).toContain('| Started | 2026-11-03 14:02 UTC |');
    expect(report).toContain(
      '| Block | Type | Status | Time | Tokens | Model | Runs |\n| --- | --- | --- | --- | --- | --- | --- |\n' +
        '| `tests` | Console | Succeeded | 3.2s | — | — | 1 |\n| `review-loop` | Loop | Succeeded |',
    );
    expect(report).toContain('## Changed files\n\nNo files changed.');
    expect(report).not.toContain('| Cost |');
    expect(report).not.toContain('| Workflow |');
    expect(report).not.toContain('deploy');
    expect(report.endsWith('Generated by Isar Flow on 2026-11-03 14:07 UTC.\n')).toBe(true);
  });

  it('reports a failed console block with the last 20 lines of its output', () => {
    const output = Array.from({ length: 30 }, (_, i) => `line ${i + 1}`).join('\n');
    const run: RunView = {
      ...successRun(),
      status: 'failure',
      error: "Block 'tests' failed: exit code 1.",
      steps: {
        tests: step(
          'failure',
          { exitCode: 1, output },
          { ...metrics(900), error: "Block 'tests' failed: exit code 1." },
        ),
      },
    };
    const report = full({ run, workflow: workflow() });
    expect(report).toContain('| Status | Failed |');
    expect(report).toContain('| Run tests (`tests`) | Console | Failed | 900ms | — | — | 1 |');
    expect(report).toContain('| `review-loop` | Loop | Not run |');
    const tail = Array.from({ length: 20 }, (_, i) => `line ${i + 11}`).join('\n');
    expect(report).toContain(
      `## Errors\n\n### Run tests (\`tests\`)\n\nBlock 'tests' failed: exit code 1.\n\n` +
        `Last 20 of 30 lines of the output (shortened):\n\n\`\`\`\n${tail}\n\`\`\`\n\n---`,
    );
  });

  it('shows short console output whole and the run error when no block has it', () => {
    const run: RunView = {
      ...successRun(),
      status: 'failure',
      error: 'The token budget of 1,000 tokens is used up.',
      steps: {
        tests: step(
          'failure',
          { exitCode: 2, stdout: 'one\r\ntwo\r\n', stderr: 'boom' },
          { ...metrics(900), error: 'Exit code 2.' },
        ),
        lint: step(
          'failure',
          { exitCode: 127 },
          {
            ...metrics(10),
            error: 'Not a <command>.',
            logs: [
              { stream: 'info', text: 'Starting\n' },
              { stream: 'stderr', text: 'not found\n' },
            ],
          },
        ),
        quiet: step('failure', { exitCode: 1 }, { ...metrics(10) }),
      },
    };
    const report = full({ run });
    expect(report).toContain(
      '## Errors\n\nThe token budget of 1,000 tokens is used up.\n\n### `tests`\n\nExit code 2.\n\n' +
        'Output:\n\n```\none\ntwo\nboom\n```\n\n### `lint`\n\nNot a \\<command>.\n\nOutput:\n\n```\nnot found\n```\n\n' +
        '### `quiet`\n\nThe block failed.\n\n---',
    );
  });

  it('marks simulated runs', () => {
    const report = full({ run: { ...successRun(), simulated: true }, review: null });
    expect(report).toContain(
      '\n\n> Simulated run: nothing was executed; results came from the simulation file.\n\n## Timeline',
    );
    expect(report).toContain("## Changed files\n\nSimulated runs don't change files.");
  });

  it('marks resumed runs and reused blocks', () => {
    const run = successRun();
    run.resumedFrom = { runId: 'run-abc', stepId: 'review-loop' };
    run.steps.tests = { ...step('success', { exitCode: 0 }), reused: true, durationMs: 0 };
    run.steps.review = { ...run.steps.review, reused: true };
    const report = full({ run, workflow: workflow() });
    expect(report).toContain(
      "> Resumed from block `review-loop` of run run-abc: blocks before it reused that run's results.",
    );
    expect(report).toContain('| Run tests (`tests`) | Console | Reused | — | — | — | — |');
    expect(report).toContain('### `review` (reused)\n\nLooks good | ship it');
  });

  it('says when outputs were shortened by the history', () => {
    const run = successRun();
    run.steps.review = { ...run.steps.review, outputTrimmed: true };
    expect(full({ run })).toContain('> Some block outputs were shortened to fit the run history.');
  });

  it('reports a cancelled run', () => {
    const run: RunView = {
      ...successRun(),
      status: 'cancelled',
      error: 'The run was cancelled.',
      steps: { tests: step('cancelled', {}, { ...metrics(1500), error: 'The run was cancelled.' }) },
    };
    const report = full({ run, workflow: workflow() });
    expect(report).toContain('| Status | Cancelled |');
    expect(report).toContain('| Run tests (`tests`) | Console | Cancelled | 1.5s |');
    expect(report).toContain('## Errors\n\nThe run was cancelled.\n\n---');
  });

  it('reports what happened so far in a running run', () => {
    const run: RunView = {
      runId: 'run-7',
      workflowName: 'Review loop',
      status: 'running',
      startedAt: STARTED,
      inputs: {},
      usage: { inputTokens: 0, outputTokens: 0 },
      activeStepId: 'review',
      steps: {
        tests: step('success', { exitCode: 0 }, metrics(3200)),
        'review-loop': { status: 'running', executions: 1, logs: [], startedAt: STARTED + 4000 },
        review: { status: 'running', executions: 1, logs: [], startedAt: STARTED + 5000 },
      },
    };
    const report = full({ run, workflow: workflow() });
    expect(report).toContain(
      '| Run | `run-7` |\n| --- | --- |\n| Status | Running |\n| Started | T+0s |\n\n',
    );
    expect(report).toContain('> The run is still running; this report shows what happened so far.');
    expect(report).toContain(`| ${NB}\`review\` | Agent | Running | — | — | — | 1 |`);
    expect(report).toContain(`| ${NB}\`fix\` | Agent | Not run | — | — | — | — |`);
    expect(report).not.toContain('Duration');
    expect(report).not.toContain('Tokens (in / out)');
  });

  it('lists blocks removed from the workflow since the run after the others', () => {
    const run = successRun();
    run.steps.lint = step('success', { exitCode: 0 }, metrics(100));
    run.steps.old = step('skipped', {}, { executions: 0 });
    const report = full({ run, workflow: workflow() });
    expect(report).toContain(
      '| `deploy` | Console | Not run | — | — | — | — |\n' +
        '| `lint` (not in the workflow anymore) | Console | Succeeded | 100ms | — | — | 1 |\n' +
        '| `old` (not in the workflow anymore) | — | Skipped | — | — | — | — |',
    );
  });

  it('names who started the run unless it was manual', () => {
    const run = {
      ...successRun(),
      origin: { kind: 'trigger' as const, trigger: 'save' as const, file: 'src/app.ts' },
    };
    expect(full({ run })).toContain('| Started by | Started on save of src/app.ts |');
    expect(full({ run: { ...successRun(), origin: { kind: 'manual' } } })).not.toContain('Started by');
    expect(full({ run: successRun(), record: recordWith({ origin: { kind: 'copilot' } }) })).toContain(
      '| Started by | Started by Copilot |',
    );
  });

  it('cuts long inputs and writes other values as JSON', () => {
    const run = {
      ...successRun(),
      inputs: { long: 'x'.repeat(300), count: 3, opts: { a: [1, 2] }, none: null },
    };
    const report = full({ run });
    expect(report).toContain(
      `| Inputs | long: ${'x'.repeat(200)}…<br>count: 3<br>opts: {"a":\\[1,2\\]}<br>none: null |`,
    );
  });

  it('shortens long agent answers, closing a code fence left open by the cut', () => {
    const run = successRun();
    const text = `Intro\n\n\`\`\`ts\n${'const x = 1;\n'.repeat(500)}\`\`\`\nAfter`;
    run.steps.review = step('success', { text }, metrics(1000));
    const report = full({ run });
    const section = report.slice(report.indexOf('### `review`'), report.indexOf('### `fix`'));
    expect(section).toMatch(/^### `review`\n\nIntro\n\n```ts\nconst x = 1;\n/);
    expect(section).toMatch(/\nconst x =…\n```\n\n\(shortened\)\n\n$/);
    expect(section.length).toBeLessThan(4100);
  });

  it('shows JSON answers pretty-printed in a fence longer than any backtick run inside', () => {
    const run = successRun();
    run.steps.review = step(
      'success',
      { text: '{}', json: { approved: false, note: 'use ```js' } },
      metrics(1),
    );
    const report = full({ run });
    expect(report).toContain(
      '### `review`\n\n````json\n{\n  "approved": false,\n  "note": "use ```js"\n}\n````\n\n### `fix`',
    );
  });

  it('keeps pipes, backticks and HTML in names and cells from breaking the tables', () => {
    const run = { ...successRun(), workflowName: 'A | B <c>' };
    const wf = workflow();
    wf.steps[0].name = 'Run `npm test` | all';
    const report = full({ run, workflow: wf, workflowPath: 'flows/a|b.yaml' });
    expect(report.startsWith('# Run report: A | B \\<c>\n')).toBe(true);
    expect(report).toContain('| Workflow | `flows/a\\|b.yaml` |');
    expect(report).toContain('| Run \\`npm test\\` \\| all (`tests`) | Console |');
  });

  it('lists review details: journal coverage, overlapping runs, omitted files and history counts', () => {
    const report = full({
      run: successRun(),
      review: review([file('a.ts'), file('b.ts', { decision: 'kept' })], {
        coverage: 'journal',
        overlapping: true,
        omitted: 4,
        omittedPending: 2,
      }),
    });
    expect(report).toContain(
      '## Changed files\n\n6 files changed: 1 kept, 3 pending.\n\n' +
        '> The folder is not a git repository, so only files that agent tools wrote are listed.\n\n' +
        '> Another run worked in the same folder at the same time, so the list may include its changes.\n\n' +
        '| File | Changes | Status | Decision | Blocks |',
    );
    expect(report).toContain(
      '| `b.ts` | +12 −3 | Modified | Kept | `fix` |\n\nAnd 4 more files that the review does not list.',
    );

    const counted = full({
      run: successRun(),
      review: review([file('a.ts')]),
      record: recordWith({ review: { total: 1, kept: 0, reverted: 1, pending: 0 } }),
    });
    expect(counted).toContain('1 file changed: 1 reverted.');
  });

  it('works for older runs without metrics', () => {
    const run = successRun();
    for (const id of Object.keys(run.steps)) {
      const { metrics: _m, durationMs: _d, ...rest } = run.steps[id];
      run.steps[id] = rest;
    }
    const report = full({ run, workflow: workflow() });
    expect(report).toContain('| Run tests (`tests`) | Console | Succeeded | — | — | — | 1 |');
  });

  it('reads lenient workflows', () => {
    const lenient = {
      version: 1,
      name: 'x',
      steps: [{ type: 'console' }, 'junk', { id: 'tests', type: 'odd' }],
    };
    const report = full({ run: successRun(), workflow: lenient as never });
    expect(report).toContain('| `tests` | Console | Succeeded | 3.2s |');
    expect(full({ run: successRun(), workflow: { steps: 'nope' } as never })).toContain(
      '| `tests` | Console |',
    );
  });

  it('says when no block ran', () => {
    const run: RunView = { ...successRun(), steps: {} };
    expect(full({ run })).toContain('## Timeline\n\nNo blocks ran.');
  });

  it('uses the workflow name of the workflow or the record when the run has none', () => {
    expect(full({ run: { ...successRun(), workflowName: '' }, workflow: workflow() })).toMatch(
      /^# Run report: Review loop\n/,
    );
    expect(full({ run: { ...successRun(), workflowName: ' ' } })).toMatch(/^# Run report: Workflow\n/);
  });
});

function recordWith(extra: object) {
  return {
    runId: 'run-42',
    workflowUri: 'file:///w.yaml',
    workflowName: 'Review loop',
    status: 'success' as const,
    startedAt: STARTED,
    ...extra,
  };
}
