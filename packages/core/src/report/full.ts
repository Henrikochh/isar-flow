import { STEP_TYPE_INFO } from '../schema/steps';
import { blockLabel, executed, STATE_LABELS } from './blocks';
import {
  agentAnswers,
  answerMarkdown,
  answerOf,
  approvalDecision,
  askAnswer,
  changesText,
  costText,
  DECISION_LABELS,
  durationText,
  errorOf,
  FILE_STATUS_LABELS,
  type Limits,
  originSentence,
  outputTail,
  promptText,
  type ReportContext,
  reviewSummary,
  RUN_STATUS_LABELS,
  runNotes,
  SHORTENED,
} from './facts';
import { code, cutChars, escapeText, formatDuration, formatNumber, oneLine, plural, table } from './format';

export const FULL_LIMITS: Limits = { answerChars: 4000, logLines: 20, files: Number.POSITIVE_INFINITY };

const INPUT_MAX_CHARS = 200;
const INDENT = '  ';

/** "Export report": summary table, notes, timeline, changed files, answers, questions, errors, footer. */
export function fullReport(ctx: ReportContext, limits: Limits, generatedAt: number): string {
  const sections = [
    `# Run report: ${escapeText(ctx.name)}`,
    summaryTable(ctx),
    ...runNotes(ctx).map((note) => `> ${note}`),
    timeline(ctx),
    changedFiles(ctx, limits),
    answers(ctx, limits),
    questions(ctx),
    errors(ctx, limits),
    `---\n\nGenerated by Isar Flow on ${escapeText(ctx.formatTime(generatedAt))}.`,
  ];
  return `${sections.filter((section) => section !== '').join('\n\n')}\n`;
}

function summaryTable(ctx: ReportContext): string {
  const { run, input } = ctx;
  const rows: string[][] = [
    ['Status', RUN_STATUS_LABELS[run.status]],
    ['Started', escapeText(ctx.formatTime(run.startedAt))],
  ];
  if (run.durationMs !== undefined) rows.push(['Duration', formatDuration(run.durationMs)]);
  if (run.usage.inputTokens + run.usage.outputTokens > 0) {
    rows.push([
      'Tokens (in / out)',
      `${formatNumber(run.usage.inputTokens)} / ${formatNumber(run.usage.outputTokens)}`,
    ]);
  }
  const cost = costText(run, input.prices);
  if (cost) rows.push(['Cost', cost]);
  const origin = originSentence(ctx);
  if (origin) rows.push(['Started by', escapeText(origin)]);
  if (input.workflowPath) rows.push(['Workflow', code(input.workflowPath)]);
  const inputs = Object.entries(run.inputs ?? {}).map(
    ([name, value]) =>
      `${escapeText(name)}: ${escapeText(cutChars(oneLine(inputText(value)), INPUT_MAX_CHARS))}`,
  );
  if (inputs.length > 0) rows.push(['Inputs', inputs.join('\n')]);
  return table(['Run', code(run.runId)], rows);
}

function inputText(value: unknown): string {
  if (typeof value === 'string') return value;
  return JSON.stringify(value) ?? String(value);
}

function timeline(ctx: ReportContext): string {
  if (ctx.blocks.length === 0) return '## Timeline\n\nNo blocks ran.';
  const rows = ctx.blocks.map((block) => {
    const metrics = block.view?.metrics;
    const usage = metrics?.usage;
    const runs = metrics?.executions ?? block.view?.executions ?? 0;
    return [
      `${INDENT.repeat(block.depth)}${blockLabel(block)}${block.removed ? ' (not in the workflow anymore)' : ''}`,
      block.type ? STEP_TYPE_INFO[block.type].label : '—',
      STATE_LABELS[block.state],
      durationText(block.view) ?? '—',
      usage ? `${formatNumber(usage.inputTokens)} / ${formatNumber(usage.outputTokens)}` : '—',
      metrics?.model ? escapeText(metrics.model) : '—',
      runs > 0 && block.state !== 'reused' ? formatNumber(runs) : '—',
    ];
  });
  return `## Timeline\n\n${table(['Block', 'Type', 'Status', 'Time', 'Tokens', 'Model', 'Runs'], rows)}`;
}

function changedFiles(ctx: ReportContext, limits: Limits): string {
  const { review } = ctx.input;
  const heading = '## Changed files';
  if (!review || (review.files.length === 0 && !review.omitted)) {
    const none = ctx.run.simulated ? "Simulated runs don't change files." : 'No files changed.';
    return `${heading}\n\n${none}`;
  }
  const parts = [heading];
  const summary = reviewSummary(ctx);
  const total = review.files.length + (review.omitted ?? 0);
  parts.push(`${plural(total, 'file')} changed${summary ? `: ${summary}` : ''}.`);
  if (review.coverage === 'journal') {
    parts.push('> The folder is not a git repository, so only files that agent tools wrote are listed.');
  }
  if (review.overlapping) {
    parts.push(
      '> Another run worked in the same folder at the same time, so the list may include its changes.',
    );
  }
  const shown = review.files.slice(0, Math.max(0, limits.files));
  if (shown.length > 0) {
    const rows = shown.map((file) => [
      code(file.path),
      changesText(file),
      FILE_STATUS_LABELS[file.status],
      DECISION_LABELS[file.decision],
      file.stepIds.length > 0 ? file.stepIds.map(code).join(', ') : 'Command',
    ]);
    parts.push(table(['File', 'Changes', 'Status', 'Decision', 'Blocks'], rows));
  }
  const cut = review.files.length - shown.length;
  if (cut > 0) parts.push(`And ${plural(cut, 'more file')} ${SHORTENED}.`);
  if (review.omitted) parts.push(`And ${plural(review.omitted, 'more file')} that the review does not list.`);
  return parts.join('\n\n');
}

function answers(ctx: ReportContext, limits: Limits): string {
  const blocks = agentAnswers(ctx.blocks);
  if (blocks.length === 0) return '';
  const parts = ['## Agent answers'];
  for (const block of blocks) {
    const answer = answerOf(block);
    if (!answer) continue;
    parts.push(`### ${blockLabel(block)}${block.state === 'reused' ? ' (reused)' : ''}`);
    parts.push(limits.answerChars > 0 ? answerMarkdown(answer, limits.answerChars) : SHORTENED);
  }
  return parts.join('\n\n');
}

function questions(ctx: ReportContext): string {
  const items: string[] = [];
  for (const block of ctx.blocks) {
    const answer = block.type === 'ask' ? askAnswer(block.view) : undefined;
    const result = answer
      ? `Answer: ${answer}`
      : block.type === 'approval'
        ? approvalDecision(block.view)
        : undefined;
    if (!result) continue;
    const prompt = promptText(block.view);
    items.push(`- ${blockLabel(block)}${prompt ? `: ${prompt}` : ''}\n  - ${result}`);
  }
  return items.length > 0 ? `## Questions and approvals\n\n${items.join('\n')}` : '';
}

function errors(ctx: ReportContext, limits: Limits): string {
  const failed = ctx.blocks.filter((block) => block.state === 'failure' && executed(block));
  const parts: string[] = [];
  const runError = ctx.run.error?.trim();
  if (runError && !failed.some((block) => errorOf(block) === runError)) {
    parts.push(escapeText(runError));
  }
  for (const block of failed) {
    parts.push(`### ${blockLabel(block)}`);
    parts.push(escapeText(errorOf(block) ?? 'The block failed.'));
    if (block.type === 'console') {
      const tail = outputTail(block.view, limits.logLines);
      if (tail) parts.push(tail);
    }
  }
  return parts.length > 0 ? `## Errors\n\n${parts.join('\n\n')}` : '';
}
