export const THEMES: Record<HarnessTheme, { bodyClass: string; vars: Record<string, string> }> = {
  dark: { bodyClass: 'vscode-dark', vars: dark },
  light: { bodyClass: 'vscode-light', vars: light },
  hc: { bodyClass: 'vscode-high-contrast', vars: hc },
  hcl: { bodyClass: 'vscode-high-contrast-light', vars: hcl },
};

export function applyTheme(theme: HarnessTheme): void {
  const { bodyClass, vars } = THEMES[theme] ?? THEMES.dark;
  document.body.classList.remove(...Object.values(THEMES).map((t) => t.bodyClass));
  document.body.classList.add(bodyClass);
  for (const [name, value] of Object.entries(vars)) document.documentElement.style.setProperty(name, value);
}
